# Take a day number (1-7) and print the correspoding day name.

day = int(input("Take a day number:- "))

if day == 1:
    print("Monday")
if day == 2:
    print("Tuesday")
if day == 3:
    print("wednesday")
if day == 4:
    print("Thursday")
if day == 5:
    print("Friday")
if day == 6:
    print("Saturday")
if day == 7:
    print("sunday")
